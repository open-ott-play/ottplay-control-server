// Build the positive corpus from the shared schema rather than copying its fields.
func perfExample(t *testing.T, fixture map[string]any, schema map[string]any) any {
	t.Helper()
	if ref, ok := schema["$ref"].(string); ok {
		return perfExample(t, fixture, fixture["$defs"].(map[string]any)[strings.TrimPrefix(ref, "#/$defs/")].(map[string]any))
	}
	if values, ok := schema["enum"].([]any); ok {
		return values[0]
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if values, ok := schema[key].([]any); ok {
			return perfExample(t, fixture, values[0].(map[string]any))
		}
	}
	kind := schema["type"]
	if values, ok := kind.([]any); ok {
		kind = values[0]
	}
	switch kind {
	case "null":
		return nil
	case "boolean":
		return false
	case "array":
		return []any{}
	case "integer", "number":
		if value, ok := schema["minimum"].(float64); ok && value > 0 {
			return value
		}
		return 0
	case "string":
		pattern, _ := schema["pattern"].(string)
		if strings.Contains(pattern, "{32}") {
			return strings.Repeat("a", 32)
		}
		if strings.HasPrefix(pattern, "^s[1-9]") {
			return "s1"
		}
		if strings.HasPrefix(pattern, "^n[1-9]") {
			return "n1"
		}
		return "page-one"
	case "object":
		v := map[string]any{}
		for _, key := range schema["required"].([]any) {
			name := key.(string)
			v[name] = perfExample(t, fixture, schema["properties"].(map[string]any)[name].(map[string]any))
		}
		return v
	}
	t.Fatalf("unhandled shared schema %v", schema)
	return nil
}

func perfParams(op string) map[string]any {
	p := map[string]any{"version": 1, "op": op, "runtime": "page-one"}
	if op != "status" {
		p["session_id"] = strings.Repeat("a", 32)
	}
	if op == "read" {
		p["after_seq"] = 0
	}
	return p
}
func perfExpected(t *testing.T, p map[string]any) *perfCaptureRequest {
	t.Helper()
	b, _ := json.Marshal(p)
	m, _ := decodeObject(b)
	result := parsePerfCaptureRequest(m)
	if result == nil {
		t.Fatal("invalid test request", p)
	}
	return result
}
func perfReply(t *testing.T, op string, kinds ...string) map[string]any {
	t.Helper()
	f := perfFixture(t)
	s := perfExample(t, f, f["$defs"].(map[string]any)["session"].(map[string]any)).(map[string]any)
	s["duration_seconds"], s["elapsed_ms"], s["remaining_ms"] = 120, 100, 119900
	s["requested"] = map[string]any{"raf": false, "long_tasks": true}
	s["supported"] = map[string]any{"raf": true, "long_tasks": true, "notification_stages": perfStages, "notification_timings": perfTimings}
	s["first_seq"], s["next_seq"], s["event_count"] = 1, len(kinds)+1, len(kinds)
	s["bytes"] = len(kinds) * 256
	if op == "stop" {
		s["state"], s["reason"], s["remaining_ms"] = "stopped", "requested", 0
	}
	v := map[string]any{"version": 1, "op": op, "runtime": "page-one", "session": s}
	if op == "read" {
		events := []any{}
		for i, kind := range kinds {
			event := perfExample(t, f, f["$defs"].(map[string]any)[kind+"_event"].(map[string]any)).(map[string]any)
			event["seq"], event["at_ms"] = i+1, i
			if kind == "loop" {
				data := event["data"].(map[string]any)
				data["raf_callbacks"], data["raf_max_gap_ms"] = nil, nil
			}
			events = append(events, event)
		}
		v["events"], v["next_after_seq"], v["more"], v["lost_before"] = events, len(kinds), false, 0
	}
	return v
}

